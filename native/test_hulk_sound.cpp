#include "hulk_sound.h"
#include <cassert>
using namespace hulkpocket;
int main(){
    XboxGuestAddressSpace mem;
    mem.Commit(0x10000,0x10000);
    XbeKernelPool pool(mem,0x200000,0x100000);
    HulkSound s(mem,pool);
    assert(s.Create(0,0x10000,0)==0);
    auto ds=mem.Read32(0x10000);assert(s.Device(ds));
    assert(!s.FullHrtfRequested());s.SelectFullHrtf();assert(s.FullHrtfRequested());
    assert(s.Speaker(ds,0x10004)==0&&mem.Read32(0x10004)==0);
    const uint8_t fmt[]={1,0,1,0,0x80,0xbb,0,0,0,0x77,1,0,2,0,16,0,0,0};
    mem.Write(0x10100,fmt,sizeof(fmt));
    const uint32_t desc[]={20,0,8,0x10100,0};
    mem.Write(0x10200,desc,sizeof(desc));
    assert(s.NewBuffer(0x10200,0x10008)==0);
    auto v=mem.Read32(0x10008);
    const int16_t pcm[]={1000,-2000,3000,-4000};
    mem.Write(0x10300,pcm,sizeof(pcm));
    assert(s.Buffer(v,kSoundBufferData,{v,0x10300,8})==0);
    assert(s.Buffer(v,kSoundBufferPlay,{v,0,0,0})==0);
    auto got=s.Render(4);
    for(unsigned i=0;i<4;++i)assert(got[2*i]==pcm[i]&&got[2*i+1]==pcm[i]);
    assert(s.Buffer(v,kSoundBufferStatus,{v,0x1000c})==0&&mem.Read32(0x1000c)==0);
    assert(s.Buffer(v,kSoundBufferPlay,{v,0,0,3})==0);
    got=s.Render(5);assert(got[8]==1000&&got[9]==1000);
    assert(s.Buffer(v,kSoundBufferPlayRegion,{v,2,6})==0);
    assert(s.Buffer(v,kSoundBufferLoopRegion,{v,2,2})==0);
    assert(s.Buffer(v,kSoundBufferPlay,{v,0,0,7})==0);
    got=s.Render(2);for(auto x:got)assert(x==0);
    assert(s.SynchPlayback(ds)==0);
    got=s.Render(4);assert(got[0]==-2000&&got[2]==3000&&got[4]==3000&&got[6]==3000);
    assert(s.Buffer(v,kSoundBufferPause,{v,1})==0);
    got=s.Render(2);for(auto x:got)assert(x==0);
    assert(s.Buffer(v,kSoundBufferPause,{v,0})==0);
    got=s.Render(1);assert(got[0]==3000);
    assert(s.Buffer(v,kSoundBufferPlayRegion,{v,1,6})==0x88780032u);
    assert(s.Buffer(v,kSoundBufferVolume,{v,uint32_t(-10000)})==0);
    got=s.Render(1);assert(got[0]==0&&got[1]==0);
    assert(s.Buffer(v,kSoundBufferData,{v,0x400000,8})==0x88780032u);
    assert(s.Buffer(v,kSoundBufferRelease,{v})==0);
    const uint8_t adpcmfmt[]={0x69,0,1,0,0x80,0xbb,0,0,0x78,0x69,0,0,36,0,4,0,2,0,64,0};
    mem.Write(0x10100,adpcmfmt,sizeof(adpcmfmt));mem.Write32(0x10208,36);
    assert(s.NewBuffer(0x10200,0x10008)==0);v=mem.Read32(0x10008);
    std::array<uint8_t,36> encoded{};encoded[0]=0x34;encoded[1]=0x12;
    mem.Write(0x10300,encoded.data(),encoded.size());
    assert(s.Buffer(v,kSoundBufferData,{v,0x10300,36})==0);
    assert(s.Buffer(v,kSoundBufferPlay,{v,0,0,0})==0);
    got=s.Render(64);for(auto x:got)assert(x==0x1234);
    assert(s.Buffer(v,kSoundBufferRelease,{v})==0);
    // XDK 5849 synthetic image with one real state segment and three
    // reserved DSP regions. Verify offset arithmetic and actual bytes.
    constexpr uint32_t img=0x12000,table=0x824;
    mem.Write32(img+0x804,1);mem.Write32(img+0x80c,2);
    mem.Write32(img+table,1);mem.Write32(img+table+4,0x1234);
    mem.Write32(img+table+16,0x900);mem.Write32(img+table+20,4);
    mem.Write32(img+0x900,0x89abcdef);
    auto before=pool.Outstanding();
    assert(s.DownloadEffects(ds,img,0x820,0,0x10010)==0x88780032u);
    assert(pool.Outstanding()==before);
    mem.Write32(img+table+4,0x1234);
    mem.Write32(img+table+12,0xffffffff);
    assert(s.DownloadEffects(ds,img,0x1000,0,0x10010)==0x88780032u);
    assert(pool.Outstanding()==before);
    mem.Write32(img+table+12,16);
    assert(s.DownloadEffects(ds,img,0x1000,0,0x10010)==0);
    auto effect=mem.Read32(0x10010);
    assert(mem.Read32(effect)==1&&mem.Read32(effect+4)==0x1234);
    assert(mem.Read32(mem.Read32(effect+16))==0x89abcdef);
    assert(s.GetEffectData(ds,0,0,0x10014,4)==0&&mem.Read32(0x10014)==0x89abcdef);
    assert(s.GetEffectData(ds,0,1,0x10014,4)==0x88780032u);
    mem.Write32(0x10018,0x11223344);
    assert(s.SetEffectData(ds,0,0,0x10018,4,1)==0x88780032u);
    assert(s.SetEffectData(ds,0,1,0x10018,4,0)==0x88780032u);
    assert(s.SetEffectData(ds,0,0,0x10018,4,0)==0);
    assert(s.GetEffectData(ds,0,0,0x10014,4)==0&&mem.Read32(0x10014)==0x11223344);
    assert(s.ReleaseDevice(ds)==0&&pool.Outstanding()==0);
    std::puts("Software DirectSound device, PCM/ADPCM, looping, volume and bounds passed");
}
